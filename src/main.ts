import { ValidationPipe } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { NestFactory } from '@nestjs/core';
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger';
import { AppModule } from './app.module';

async function bootstrap() {
  // rawBody: keep the exact bytes of each request so webhook HMAC signatures
  // (Razorpay) can be verified against what the provider actually signed.
  const app = await NestFactory.create(AppModule, { rawBody: true });
  const config = app.get(ConfigService);

  // Trust the first proxy hop so req.ip / X-Forwarded-For is the REAL client IP —
  // required for per-client rate limiting behind a load balancer.
  const http = app.getHttpAdapter().getInstance() as {
    set: (k: string, v: unknown) => void;
  };
  http.set('trust proxy', 1);

  // Drain in-flight work + close the DB pool cleanly on SIGTERM/SIGINT (rolling
  // deploys / autoscale) instead of cutting connections.
  app.enableShutdownHooks();

  app.useGlobalPipes(
    new ValidationPipe({
      whitelist: true,
      forbidNonWhitelisted: true,
      transform: true,
    }),
  );

  // CORS: permissive for now — reflect ANY request origin (works with
  // credentials, unlike a literal '*'). Effectively allow-all across dev ports.
  // TODO (pre-prod): switch to the FRONTEND_URL/CORS_ORIGINS allow-list.
  const isProd = config.get<string>('NODE_ENV') === 'production';
  const allowlist = [
    config.get<string>('FRONTEND_URL'),
    ...(config.get<string>('CORS_ORIGINS') ?? '')
      .split(',')
      .map((o) => o.trim()),
  ].filter((o): o is string => Boolean(o));
  app.enableCors({
    // Enforce the allow-list only in production; otherwise reflect any origin.
    origin: isProd && allowlist.length > 0 ? allowlist : true,
    credentials: true,
  });

  // OpenAPI / Swagger UI at /docs. Enabled outside production (or when DEBUG=true)
  // per the migration spec. DTO schemas + validation rules are auto-generated by
  // the @nestjs/swagger CLI plugin (nest-cli.json). Use the Authorize button to
  // paste a Bearer access token for the protected routes.
  const debug = config.get<string>('DEBUG') === 'true';
  if (debug || !isProd) {
    const docConfig = new DocumentBuilder()
      .setTitle('Shuddha Bharat API')
      .setDescription(
        'Storefront + admin commerce API (auth, catalog, cart, wishlist, ' +
          'addresses, orders, payment, shipping, webhooks).',
      )
      .setVersion('1.0')
      .addBearerAuth(
        { type: 'http', scheme: 'bearer', bearerFormat: 'JWT' },
        'BearerAuth',
      )
      .build();
    const document = SwaggerModule.createDocument(app, docConfig);
    // Apply the Bearer scheme globally so the Authorize token is sent on every
    // "Try it out" (public routes simply ignore it). Avoids decorating every
    // controller with @ApiBearerAuth.
    document.security = [{ BearerAuth: [] }];
    SwaggerModule.setup('docs', app, document, {
      swaggerOptions: { persistAuthorization: true },
    });
  }

  await app.listen(config.get<number>('PORT', 3001));
}
void bootstrap();
